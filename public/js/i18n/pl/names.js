// Polish content names (the Polish twin of i18n/bg/names.js). Keyed by content id; 'family:id' overrides an id that two
// families share. Loaded only when Polish is chosen (i18n/names.js). Entry shape (docs/i18n-polish-guide.md):
//   { name, g: 'm' | 'f' | 'n' | 'pl', pl, gen, acc, genSg, short?, lc?, proper?, one?, unit?: [after 1, 2-4, 5+], desc? }
//   name label (sentence case), pl nominative plural, gen genitive plural (after 5+), acc accusative singular,
//   genSg genitive singular; unit: a mass noun's counting word ("3 snopy pszenicy" with genSg).
const lc = (s) => s[0].toLocaleLowerCase('pl') + s.slice(1);
/** Masculine inanimate (accusative = nominative). */
const m = (name, pl, gen, genSg, extra = {}) => ({ name, g: 'm', pl, gen, acc: lc(name), genSg, ...extra });
/** Masculine animate (accusative = genitive). */
const ma = (name, pl, gen, genSg, extra = {}) => ({ name, g: 'm', pl, gen, acc: genSg, genSg, ...extra });
const f = (name, pl, gen, acc, genSg, extra = {}) => ({ name, g: 'f', pl, gen, acc, genSg, ...extra });
/** Neuter (accusative = nominative). */
const n = (name, pl, gen, genSg, extra = {}) => ({ name, g: 'n', pl, gen, acc: lc(name), genSg, ...extra });
/** A plural noun ("Naleśniki"): `one` is the singular after 1; non-virile, so accusative = nominative. */
const plural = (name, gen, one, extra = {}) => ({ name, g: 'pl', pl: lc(name), gen, acc: lc(name), genSg: gen, one, ...extra });
/** A mass noun counted in units, masculine inanimate / neuter / plural (accusative = nominative). */
const mass = (name, g, genSg, unit, extra = {}) => ({ name, g, acc: lc(name), genSg, unit, ...extra });
/** A feminine mass noun counted in units. */
const fmass = (name, acc, genSg, unit, extra = {}) => ({ name, g: 'f', acc, genSg, unit, ...extra });
/** "<head> <tail>": a head entry whose tail never changes ("Muffinka" + "z marchewką"). */
const tail = (e, t, extra = {}) => {
  const o = { ...e };
  for (const k of ['name', 'pl', 'gen', 'acc', 'genSg', 'lc', 'one']) if (o[k]) o[k] = `${o[k]} ${t}`;
  return { ...o, ...extra };
};
/** A proper name with no plural (a ribbon, a feature, a place): keeps its capital in a sentence. */
const one = (name, g, acc = name, genSg = name, extra = {}) => ({ name, g, proper: true, acc, genSg, ...extra });
